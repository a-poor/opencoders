use serde_json::{Map, Value, json};
use std::collections::BTreeSet;

/// Select named schemas and their transitive dependencies for generation.
pub fn select_schemas(spec: &Value, roots: &[&str]) -> Result<Value, String> {
    let schemas = spec
        .pointer("/components/schemas")
        .and_then(Value::as_object)
        .ok_or("missing components/schemas")?;
    let mut pending: BTreeSet<String> = roots.iter().map(|name| (*name).into()).collect();
    let mut selected = Map::new();
    while let Some(name) = pending.pop_first() {
        if selected.contains_key(&name) {
            continue;
        }
        let mut schema = schemas
            .get(&name)
            .ok_or_else(|| format!("missing schema: {name}"))?
            .clone();
        rewrite_refs(&mut schema, &mut pending)?;
        selected.insert(name, schema);
    }
    Ok(json!({"$schema": "http://json-schema.org/draft-07/schema#", "definitions": selected}))
}

fn rewrite_refs(value: &mut Value, pending: &mut BTreeSet<String>) -> Result<(), String> {
    match value {
        Value::Object(map) => {
            if let Some(reference) = map.get("$ref") {
                let reference = reference.as_str().ok_or("non-string $ref")?;
                let name = reference
                    .strip_prefix("#/components/schemas/")
                    .ok_or_else(|| format!("unsupported reference: {reference}"))?;
                pending.insert(name.replace("~1", "/").replace("~0", "~"));
                let rewritten = format!("#/definitions/{name}");
                map.insert("$ref".into(), Value::String(rewritten));
            }
            for child in map.values_mut() {
                rewrite_refs(child, pending)?;
            }
        }
        Value::Array(items) => {
            for item in items {
                rewrite_refs(item, pending)?;
            }
        }
        _ => {}
    }
    Ok(())
}

pub fn generate(
    schema: Value,
    non_null_override: bool,
) -> Result<String, Box<dyn std::error::Error>> {
    let mut settings = typify::TypeSpaceSettings::default();
    if non_null_override {
        settings.with_conversion(
            serde_json::from_value(json!({"not": {"type": "null"}}))?,
            "crate::compat::NonNullValue",
            std::iter::empty(),
        );
    }
    generate_with_settings(schema, &settings)
}

pub(crate) fn generate_with_settings(
    schema: Value,
    settings: &typify::TypeSpaceSettings,
) -> Result<String, Box<dyn std::error::Error>> {
    let mut types = typify::TypeSpace::new(settings);
    types.add_root_schema(serde_json::from_value::<schemars::schema::RootSchema>(
        schema,
    )?)?;
    let syntax = syn::parse2(types.to_stream())?;
    Ok(format!(
        "// Generated by model-spike. Do not edit manually.\n{}",
        prettyplease::unparse(&syntax)
    ))
}
